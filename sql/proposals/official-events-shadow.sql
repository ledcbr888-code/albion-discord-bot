-- PROPOSAL ONLY: Official GameInfo Events Shadow observations.
-- Apply to the same Supabase project used by the existing Battleboard collector
-- only after the bot PR and target database are reviewed. Do not run automatically.
--
-- The bot stores one first-observed row per Battle ID, not every Kill Event.
-- No production Battle, report, queue, or Auto-Battle state is changed.

create table if not exists public.discovery_observations (
  id bigint generated by default as identity primary key,
  source text not null
    check (source = 'official_events_shadow'),
  server text not null
    check (server = 'asia'),
  battle_id bigint not null,
  event_id text,
  observed_at timestamptz not null,
  event_time timestamptz,
  battle_finished_at timestamptz,
  raw_payload jsonb,
  -- NULL means the Bot could not verify Battle List state during the first
  -- observation (for example, the history lookup was unavailable).
  is_new_battle boolean,
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  constraint discovery_observations_source_server_battle_unique
    unique (source, server, battle_id)
);

create index if not exists discovery_observations_shadow_observed_idx
  on public.discovery_observations (source, server, observed_at desc);

create index if not exists discovery_observations_shadow_expiry_idx
  on public.discovery_observations (expires_at);

comment on table public.discovery_observations is
  'Three-day, Asia-only Official GameInfo Events Shadow samples. Exactly one first-observed row per Battle ID; never used to create production Battle reports.';

comment on column public.discovery_observations.observed_at is
  'Time the existing Discord Bot Process first observed an Event carrying this Battle ID.';

comment on column public.discovery_observations.event_time is
  'In-game kill-event TimeStamp; not the Battle finished timestamp.';

comment on column public.discovery_observations.is_new_battle is
  'True if Battle List had not seen this Battle at first Events observation, false if already seen, NULL if lookup failed.';

alter table public.discovery_observations enable row level security;
revoke all on table public.discovery_observations from anon, authenticated;
grant select, insert, update, delete on table public.discovery_observations to service_role;
grant usage, select on sequence public.discovery_observations_id_seq to service_role;
